    def get_cluster_statistics(self):
        """Print and return a DataFrame of total / singleton cluster counts.

        Reports statistics for every (fingerprint_type, threshold) combination
        currently stored in ``self.cluster_data``.  Mirrors the inline stats
        block from the original notebook exploration::

            Total Clusters | Singleton Clusters | Fraction Singleton

        Returns
        -------
        pd.DataFrame with columns:
            fingerprint_type, threshold, total_clusters,
            singleton_clusters, fraction_singleton
        """
        rows = []
        print("\nCluster Statistics by Fingerprint Type and Threshold:")
        print(
            f"{'FP Type':<10} {'Threshold':<12} {'Total':<15} "
            f"{'Singletons':<20} {'Fraction Singleton'}"
        )
        print("-" * 70)

        for key, data in sorted(self.cluster_data.items()):
            fp_type   = data["fingerprint_type"]
            threshold = data["threshold"]
            cliff_ids = data["cliff_ids"]

            total     = len(cliff_ids)
            singletons = sum(1 for c in cliff_ids if len(c) == 1)
            fraction  = singletons / total if total > 0 else 0.0

            print(
                f"{fp_type:<10} {threshold:<12.2f} {total:<15} "
                f"{singletons:<20} {fraction:<20.4f}"
            )
            rows.append(
                {
                    "fingerprint_type":   fp_type,
                    "threshold":          threshold,
                    "total_clusters":     total,
                    "singleton_clusters": singletons,
                    "fraction_singleton": fraction,
                }
            )

        return pd.DataFrame(rows)

    def plot_cluster_size_distribution(self, fp_type: str = None, save_path: str = None, dpi: int = 600):
        """Plot the distribution of cluster sizes for each threshold.

        Parameters
        ----------
        fp_type   : str, optional
            Filter to a single fingerprint type.  Defaults to the first
            available type.
        save_path : str, optional
            File path for saving the figure.  If None the figure is not saved.
        dpi       : int
            Resolution for saved figure (default 600).
        """
        if self.df_results.empty:
            print("No results found. Run a clustering method first.")
            return

        df = self.df_results

        if "cluster_std" in df.columns:
            # from perform_maximal_smooth_interval_clustering
            col_cliff_std  = "cluster_std"
            col_smooth_std = "smooth_std"
            col_rank       = "rank"
        elif "cliff_p_std" in df.columns and "smooth_p_std" in df.columns:
            # from perform_exhaustive_posthoc_smooth_clustering
            col_cliff_std  = "cliff_p_std"
            col_smooth_std = "smooth_p_std"
            col_rank       = "cluster_index"
        else:
            print("Required columns for plotting not present.")
            return

        if fp_type is None:
            fp_type = df["fingerprint_type"].iloc[0]

        df = df[df["fingerprint_type"] == fp_type]
        thresholds = sorted(df["threshold"].unique())
        colors     = plt.cm.viridis(np.linspace(0, 1, len(thresholds)))

        fig, ax = plt.subplots(figsize=(10, 6))

        for threshold, color in zip(thresholds, colors):
            sub = df[df["threshold"] == threshold].sort_values(col_rank)
            
            # Filter out NaNs if any (e.g. from subclusters with no parent cliff cluster stats)
            sub = sub.dropna(subset=[col_cliff_std, col_smooth_std])
            
            ax.plot(sub[col_rank], sub[col_cliff_std],
                    color=color, linestyle="-", linewidth=1.5,
                    marker="o", markersize=4,
                    label=f"Cluster std  th={threshold:.2f}")
            ax.plot(sub[col_rank], sub[col_smooth_std],
                    color=color, linestyle="--", linewidth=1.5,
                    marker="o", markersize=4,
                    label=f"Smooth std   th={threshold:.2f}")

        ax.set_xlabel("Cluster Rank" if col_rank == "rank" else "Subcluster Index")
        ax.set_ylabel("Property Std")
        ax.set_title(f"{fp_type}: Cluster Std vs Smooth Interval Std")
        ax.set_xticks(df[col_rank].unique())
        ax.legend(
            loc="upper left", bbox_to_anchor=(1.01, 1),
            fontsize=7.5, borderaxespad=0, frameon=True,
        )
        plt.tight_layout()

        if save_path:
            plt.savefig(save_path, dpi=dpi, bbox_inches="tight")
            print(f"Plot saved → {save_path}")

        plt.show()
