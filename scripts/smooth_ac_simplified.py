"""Simplified smooth/cliff clustering and visualization pipeline.

This file is a cleaned copy of smooth_ac.py with redundant comparison and
matrix-analysis utilities removed. It keeps:
- data loading
- standard cliff + smooth clustering
- exhaustive post-hoc smooth clustering
- molecule visualization compatible with cluster_data[<fp>_<threshold>]['smooth_ids']
- CSV export of summary statistics
"""

import os
import re
import sys
from collections import defaultdict

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from IPython.display import SVG, display
from rdkit import Chem
from rdkit.Chem import Draw

sys.path.append(os.path.join(os.path.dirname(__file__), ".."))
from bb_utils import bb_ac


def _increase_svg_font_size(svg_str, scale_factor=2.0):
    """Increase legend font sizes in an SVG generated by RDKit."""

    def scale_font(match):
        current_size = float(match.group(1))
        return f'font-size="{current_size * scale_factor}px"'

    return re.sub(r'font-size="([\d.]+)px"', scale_font, svg_str)


class FingerprintClusterAnalyzer:
    """Minimal analyzer for cliff/smooth clustering and molecule visualization."""

    def __init__(self, fingerprint_types=None, thresholds=None, top=10):
        self.fingerprint_types = fingerprint_types or ["ECFP", "MACCS", "RDKIT"]
        self.thresholds = thresholds if thresholds is not None else [0.95]
        self.top = top
        self.fingerprint_data = {}
        self.property_data = {}
        self.cluster_data = defaultdict(dict)
        self.results = []
        self.df_results = pd.DataFrame()

    def load_fingerprint_data(self, data_prefix="CHEMBL234_Ki_fp", prop_prefix="CHEMBL234_Ki_fp", data_dir="files"):
        """Load fingerprint and property arrays for all configured fingerprint types."""
        self.fingerprint_data = {}
        self.property_data = {}

        for fp_type in self.fingerprint_types:
            fps_file = f"{data_dir}/fps_{data_prefix}_{fp_type}.npy"
            props_file = f"{data_dir}/props_{prop_prefix}_{fp_type}.npy"

            try:
                self.fingerprint_data[fp_type] = np.load(fps_file)
                self.property_data[fp_type] = np.load(props_file)
                print(f"Loaded {fp_type}: {self.fingerprint_data[fp_type].shape[0]} molecules")
            except FileNotFoundError as exc:
                print(f"Warning: Could not load {fp_type} data - {exc}")

    def _fit_cliff_clusters(self, fps, props, threshold):
        bb_ac.activity_cliffs = True
        model = bb_ac.BitBirch(threshold=threshold)
        model.fit(fps, props)
        return model.get_cluster_mol_ids()

    def _fit_smooth_clusters(self, fps, props, threshold):
        bb_ac.activity_cliffs = False
        model = bb_ac.BitBirch(threshold=threshold)
        model.fit(fps, props)
        return model.get_cluster_mol_ids()

    def perform_clustering(self):
        """Run standard BitBIRCH cliff and smooth clustering."""
        self.cluster_data = defaultdict(dict)
        self.results = []

        for fp_type in self.fingerprint_types:
            if fp_type not in self.fingerprint_data:
                print(f"Skipping {fp_type} - data not loaded")
                continue

            fps = self.fingerprint_data[fp_type]
            props = self.property_data[fp_type]
            print(f"\nProcessing {fp_type} fingerprints...")

            for threshold in self.thresholds:
                print(f"  Threshold: {threshold}")
                cliff_ids = self._fit_cliff_clusters(fps, props, threshold)
                smooth_ids = self._fit_smooth_clusters(fps, props, threshold)

                key = f"{fp_type}_{threshold}"
                self.cluster_data[key] = {
                    "fingerprint_type": fp_type,
                    "threshold": threshold,
                    "cliff_ids": cliff_ids,
                    "smooth_ids": smooth_ids,
                    "properties": props,
                }

                print(f"    Cliff clusters: {len(cliff_ids)}")
                print(f"    Smooth clusters: {len(smooth_ids)}")

                for idx, (cliff_cluster, smooth_cluster) in enumerate(zip(cliff_ids[: self.top], smooth_ids[: self.top])):
                    cliff_props = props[cliff_cluster]
                    smooth_props = props[smooth_cluster]
                    self.results.append(
                        {
                            "fingerprint_type": fp_type,
                            "threshold": threshold,
                            "cluster_index": idx,
                            "cliff_nmols": len(cliff_cluster),
                            "smooth_nmols": len(smooth_cluster),
                            "cliff_p_mean": float(np.mean(cliff_props)),
                            "cliff_p_std": float(np.std(cliff_props)),
                            "smooth_p_mean": float(np.mean(smooth_props)),
                            "smooth_p_std": float(np.std(smooth_props)),
                        }
                    )

        self.df_results = pd.DataFrame(self.results)

    def perform_exhaustive_posthoc_smooth_clustering(self, property_span=1.0, top_subclusters=20):
        """Generate smooth clusters post hoc from cliff clusters.

        Each cliff cluster is sorted by property and greedily partitioned into
        subclusters whose property span is <= property_span.
        The selected top_subclusters are stored as smooth_ids for visualization.
        """
        self.cluster_data = defaultdict(dict)
        self.results = []

        for fp_type in self.fingerprint_types:
            if fp_type not in self.fingerprint_data:
                print(f"Skipping {fp_type} - data not loaded")
                continue

            fps = self.fingerprint_data[fp_type]
            props = self.property_data[fp_type]
            print(f"\nProcessing {fp_type} fingerprints (post-hoc smooth)...")

            for threshold in self.thresholds:
                print(f"  Threshold: {threshold}")
                cliff_ids = self._fit_cliff_clusters(fps, props, threshold)
                all_clusters = sorted(cliff_ids, key=len, reverse=True)

                threshold_subclusters = []
                for cluster_rank, cluster in enumerate(all_clusters, 1):
                    mol_ids = list(cluster)
                    cluster_props = props[mol_ids]

                    order = np.argsort(cluster_props)
                    sorted_ids = [mol_ids[i] for i in order]
                    sorted_props = cluster_props[order]

                    left = 0
                    sub_idx = 0
                    n = len(sorted_props)
                    while left < n:
                        right = left
                        while right + 1 < n and (sorted_props[right + 1] - sorted_props[left] <= property_span):
                            right += 1

                        sub_props = sorted_props[left : right + 1]
                        threshold_subclusters.append(
                            {
                                "threshold": threshold,
                                "fingerprint_type": fp_type,
                                "cluster_rank": cluster_rank,
                                "cluster_size": n,
                                "subcluster_idx": sub_idx,
                                "subcluster_size": right - left + 1,
                                "prop_min": float(sub_props[0]),
                                "prop_max": float(sub_props[-1]),
                                "prop_range": float(sub_props[-1] - sub_props[0]),
                                "prop_std": float(np.std(sub_props)),
                                "mol_ids": sorted_ids[left : right + 1],
                            }
                        )

                        sub_idx += 1
                        left = right + 1

                selected_subclusters = sorted(
                    threshold_subclusters,
                    key=lambda x: (x["subcluster_size"], x["prop_std"]),
                    reverse=True,
                )[:top_subclusters]

                smooth_ids = [sub["mol_ids"] for sub in selected_subclusters]
                key = f"{fp_type}_{threshold}"
                self.cluster_data[key] = {
                    "fingerprint_type": fp_type,
                    "threshold": threshold,
                    "cliff_ids": cliff_ids,
                    "smooth_ids": smooth_ids,
                    "properties": props,
                    "posthoc_top_subclusters": selected_subclusters,
                }

                print(f"    Cliff clusters: {len(cliff_ids)}")
                print(f"    Post-hoc smooth subclusters kept: {len(smooth_ids)}")

                for idx, sub in enumerate(selected_subclusters):
                    cliff_cluster = cliff_ids[idx] if idx < len(cliff_ids) else []
                    cliff_props = props[cliff_cluster] if len(cliff_cluster) else np.array([])
                    smooth_props = props[sub["mol_ids"]]
                    self.results.append(
                        {
                            "fingerprint_type": fp_type,
                            "threshold": threshold,
                            "cluster_index": idx,
                            "cliff_nmols": int(len(cliff_cluster)) if len(cliff_cluster) else np.nan,
                            "smooth_nmols": int(sub["subcluster_size"]),
                            "cliff_p_mean": float(np.mean(cliff_props)) if len(cliff_props) else np.nan,
                            "cliff_p_std": float(np.std(cliff_props)) if len(cliff_props) else np.nan,
                            "smooth_p_mean": float(np.mean(smooth_props)),
                            "smooth_p_std": float(sub["prop_std"]),
                            "smooth_parent_cluster_rank": int(sub["cluster_rank"]),
                            "smooth_prop_range": float(sub["prop_range"]),
                        }
                    )

        self.df_results = pd.DataFrame(self.results)

