    def perform_maximal_smooth_interval_clustering(
        self,
        property_span: float = 1.0,
        top_n: int = 20,
    ):
        """Find the maximal contiguous smooth interval inside each cliff cluster.

        For every cliff cluster the molecules are sorted by property value and a
        two-pointer sliding window identifies the **longest** subarray where
        ``max - min <= property_span``.  Unlike
        ``perform_exhaustive_posthoc_smooth_clustering``, which greedily
        partitions the full cluster into non-overlapping windows, this method
        picks the single best (largest) window per cluster.

        The ``top_n`` clusters ranked by size are examined and their results are
        stored in ``self.cluster_data[key]['smooth_ids']`` so that
        ``visualize_molecules`` works without modification.

        Per-cluster statistics recorded
        --------------------------------
        cluster_size    : total molecules in the cliff cluster
        cluster_std     : std of all property values in the cliff cluster
        smooth_interval : number of molecules in the maximal smooth window
        smooth_std      : std of the property values inside that window
        interval_min    : lowest property value in the window
        interval_max    : highest property value in the window
        interval_range  : interval_max - interval_min

        Parameters
        ----------
        property_span : float
            Maximum allowed ``max - min`` within a smooth interval (default 1.0).
        top_n : int
            Number of largest cliff clusters to process (default 20).
        """
        self.cluster_data = defaultdict(dict)
        self.results = []

        for fp_type in self.fingerprint_types:
            if fp_type not in self.fingerprint_data:
                print(f"Skipping {fp_type} - data not loaded")
                continue

            fps   = self.fingerprint_data[fp_type]
            props = self.property_data[fp_type]
            print(f"\nProcessing {fp_type} fingerprints (maximal smooth interval)...")

            for threshold in self.thresholds:
                print(f"  Threshold: {threshold}")
                print(
                    f"  {'Rank':<6} {'Cluster Size':<15} "
                    f"{'Cluster Std':<15} {'Smooth Interval':<18} "
                    f"{'Smooth Std':<12} {'Property Range'}"
                )
                print("  " + "-" * 80)

                cliff_ids = self._fit_cliff_clusters(fps, props, threshold)
                top_clusters = sorted(cliff_ids, key=len, reverse=True)[:top_n]

                smooth_ids = []  # list of mol-id lists, one per processed cluster

                for rank, cluster in enumerate(top_clusters, 1):
                    mol_ids      = list(cluster)
                    cluster_props = props[mol_ids]

                    # Sort by property value
                    order         = np.argsort(cluster_props)
                    sorted_ids    = [mol_ids[i] for i in order]
                    sorted_props  = cluster_props[order]

                    cluster_std = float(np.std(cluster_props))

                    # Two-pointer sliding window: longest window with
                    # sorted_props[r] - sorted_props[l] <= property_span
                    best_len, best_l = 1, 0
                    l = 0
                    for r in range(len(sorted_props)):
                        while sorted_props[r] - sorted_props[l] > property_span:
                            l += 1
                        if r - l + 1 > best_len:
                            best_len = r - l + 1
                            best_l   = l

                    interval_ids   = sorted_ids[best_l : best_l + best_len]
                    interval       = sorted_props[best_l : best_l + best_len]
                    smooth_std     = float(np.std(interval))
                    interval_range = float(interval[-1] - interval[0])

                    smooth_ids.append(interval_ids)

                    print(
                        f"  {rank:<6} {len(cluster):<15} {cluster_std:<15.3f} "
                        f"{best_len:<18} {smooth_std:<12.3f} "
                        f"[{interval[0]:.3f}, {interval[-1]:.3f}]  "
                        f"(range={interval_range:.3f})"
                    )

                    self.results.append(
                        {
                            "fingerprint_type": fp_type,
                            "threshold":        threshold,
                            "rank":             rank,
                            "cluster_size":     len(cluster),
                            "cluster_std":      cluster_std,
                            "smooth_interval":  best_len,
                            "smooth_std":       smooth_std,
                            "interval_min":     float(interval[0]),
                            "interval_max":     float(interval[-1]),
                            "interval_range":   interval_range,
                        }
                    )

                key = f"{fp_type}_{threshold}"
                self.cluster_data[key] = {
                    "fingerprint_type": fp_type,
                    "threshold":        threshold,
                    "cliff_ids":        cliff_ids,
                    "smooth_ids":       smooth_ids,
                    "properties":       props,
                }

                print(f"  Cliff clusters : {len(cliff_ids)}")
                print(f"  Top-{top_n} processed, smooth intervals stored: {len(smooth_ids)}")

        self.df_results = pd.DataFrame(self.results)

